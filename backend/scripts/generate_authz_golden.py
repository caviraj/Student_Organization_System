#!/usr/bin/env python
"""Record today's authorisation behaviour into tests/fixtures/authz_golden.json.

Run this against the code you are about to refactor, commit the fixture, and then change things.
`tests/test_authz_golden.py` replays the same matrix afterwards and fails on any cell that moved
without being declared in tests/fixtures/authz_intended_changes.json.

The same seeding and probing code is used by both runs (tests/authz_golden.py): a fixture recorded
one way and replayed another would prove nothing.

Environment mirrors tests/conftest.py on purpose - cheap bcrypt, no rate limits, mock payments,
local storage - so the recorded matrix describes the app the test suite exercises.

    python scripts/generate_authz_golden.py            # record the whole matrix
    python scripts/generate_authz_golden.py --merge    # add rows for routes with no recorded answer

`--merge` exists because re-recording from today's code would prove nothing about the refactor: it
is how a phase that adds routes records just those, leaving every other cell as evidence. Every
route the fixture has and the app no longer does - and every route the app has that the fixture did
not - is printed, so the change is read rather than assumed.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
# core/config.py reads .env relative to the working directory.
os.chdir(BACKEND)

os.environ.setdefault("JWT_SECRET", "test-secret-long-enough-for-hs256-32-bytes")
os.environ["BCRYPT_ROUNDS"] = "4"
os.environ["STORAGE_PROVIDER"] = "local"
os.environ["LOCAL_STORAGE_DIR"] = tempfile.mkdtemp(prefix="ssa-golden-receipts-")
os.environ["RATE_LIMIT_ENABLED"] = "false"
os.environ["PAYMENTS_PROVIDER"] = "mock"

from alembic.config import Config
from sqlalchemy import create_engine

from alembic import command
from app.core.config import settings
from app.core.db import duplicate_database_reason, engine_kwargs
from app.main import app
from tests.authz_golden import GOLDEN_PATH, LEGACY_ROLES, collect, make_harness


def _git_head() -> str:
    """Recorded so a reader can tell which commit a fixture describes."""
    result = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"],
        cwd=BACKEND,
        capture_output=True,
        text=True,
        check=False,
    )
    return result.stdout.strip() or "unknown"


def _write_golden(matrix: dict, path: Path, merge: bool) -> None:
    """Write the whole matrix, or only the rows the existing fixture does not have.

    In merge mode the existing `note` and `recorded_from` are kept: the fixture still describes the
    code it was recorded from, and only the new routes are recorded against today's.
    """
    existing = json.loads(path.read_text(encoding="utf-8")) if merge and path.exists() else {}
    recorded = existing.get("routes", {})
    added = sorted(set(matrix) - set(recorded))
    lost = sorted(set(recorded) - set(matrix))

    document = {
        "note": existing.get(
            "note",
            "Authorisation behaviour before the M2-P2 RBAC refactor. Generated by "
            "scripts/generate_authz_golden.py; replayed by tests/test_authz_golden.py.",
        ),
        "recorded_from": existing.get("recorded_from") or _git_head(),
        "roles": list(LEGACY_ROLES),
        "routes": {**recorded, **matrix} if merge else matrix,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    if merge:
        print(f"merged into   : {path.relative_to(BACKEND)}")
        print(f"routes added  : {len(added)}")
        for key in added:
            print(f"  {key}")
        print(f"routes lost   : {len(lost)}")
        for key in lost:
            print(f"  {key}")


def _audit(matrix: dict) -> None:
    """The audit, printed rather than read out of the JSON."""
    unguarded = []
    admin_denied = []
    crashing = []
    for key, row in sorted(matrix.items()):
        if all(row[role] == "allow" for role in LEGACY_ROLES):
            unguarded.append(key)
        if row["admin"] == "deny":
            admin_denied.append(key)
        for role in LEGACY_ROLES:
            if row[role] == "error":
                crashing.append(f"{key} [{role}] -> {row[f'_{role}_status']}")

    print(f"routes        : {len(matrix)}")
    print(f"cells         : {len(matrix) * len(LEGACY_ROLES)}")
    print()
    print(f"allowed for EVERY role, including guest ({len(unguarded)}) - check each is public by design:")
    for key in unguarded:
        print(f"  {key}")
    print()
    print(f"denied for admin ({len(admin_denied)}):")
    for key in admin_denied:
        print(f"  {key}")
    if crashing:
        print()
        print(f"500 on an empty body ({len(crashing)}) - the handler broke, not an authz answer:")
        for line in crashing:
            print(f"  {line}")


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    merge = "--merge" in argv
    if merge and not GOLDEN_PATH.exists():
        print("refusing --merge: there is no golden matrix to merge into", file=sys.stderr)
        return 2

    reason = duplicate_database_reason(settings.TEST_DATABASE_URL, settings.DATABASE_URL)
    if reason:
        print(f"refusing to run: {reason}", file=sys.stderr)
        return 2

    test_url = settings.TEST_DATABASE_URL
    config = Config(str(BACKEND / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND / "alembic"))
    os.environ["ALEMBIC_DATABASE_URL"] = test_url
    command.upgrade(config, "head")

    engine = create_engine(test_url, **engine_kwargs(test_url))
    client, reset = make_harness(app, engine)
    try:
        matrix = collect(client, app, reset)
    finally:
        app.dependency_overrides.clear()
        engine.dispose()

    _write_golden(matrix, GOLDEN_PATH, merge)
    _audit(matrix)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
