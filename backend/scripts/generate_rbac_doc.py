"""Write `docs/RBAC.md` from the permission catalog and the running app.

    python scripts/generate_rbac_doc.py [--check]

Two readers, two halves. The catalog half is for whoever decides who may do what: every permission,
grouped by area, with the privileged ones marked. The route-map half is for whoever is holding a
token and has just been refused: it says which permission each endpoint actually asks for, read off
the dependency the route declares - not off a comment that has since stopped being true.

Like `scripts/export_openapi.py`, this is a pure function of the code, and `--check` exits non-zero
if the committed file is stale. `tests/test_rbac.py` runs the same comparison, so a new permission
that nobody re-rendered fails the suite rather than being discovered by a reader.
"""

from __future__ import annotations

import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from app.core.permissions import BY_CATEGORY, PRIVILEGED_ROLES, ROLE_PERMISSIONS, ROLE_SPECS
from app.core.routes import iter_api_routes
from app.main import app
from app.services.rbac import SOD_PAIRS

DEST = BACKEND_DIR.parent / "docs" / "RBAC.md"

HEADER = """# RBAC - permissions, roles and the route map

Generated by `scripts/generate_rbac_doc.py`. **Do not edit by hand** - run the script instead, and
CI (or `python scripts/generate_rbac_doc.py --check`) fails if this file is stale.

The source of truth is `backend/app/core/permissions.py`. Every permission key in the codebase is a
constant in that module, and `require_permission` validates the key a route names against it *at
import time* - so a typo is a crash when the app boots, never a silent 403 for a real user later.
The `permissions` / `roles` tables are that module's synced copy (both the migration and
`scripts/seed.py` call `sync_catalog`), and `tests/test_rbac.py` fails if the two disagree.

**How a user's access is decided.** A request is allowed when the user holds *any* of the keys the
route names. Those keys come from two places: `users.role`, the single global role every phase-1
route already keyed off, and `user_roles` - a second role, a role scoped to one event or fundraiser,
or a role with an end date. An assignment counts only while it is live (`revoked_at IS NULL` and
inside its `valid_from`/`valid_to` window), so a term handover is a date rather than a cleanup job.
A **scoped** assignment grants its permissions only on the resource it names; anything unscoped
ignores it entirely.

Roles are **nested**: each rung holds everything below it. That nesting is what made the move from
role strings to permissions a provable no-op - `tests/fixtures/authz_golden.json` records every
(route, legacy role) answer from before the refactor, and `tests/test_authz_golden.py` replays all
of them. `secretary`, `event_lead` and `auditor` sit **outside** the ladder on purpose.

## The ladder
"""


def guard_keys(route) -> tuple[str, ...]:
    """The permission keys a route's dependencies declare, in declaration order.

    Public because `tests/test_rbac.py` uses it to prove every guarded route has a row here.
    """
    keys: list[str] = []
    stack = [route.dependant]
    while stack:
        dependant = stack.pop(0)
        declared = getattr(dependant.call, "required_permissions", None)
        if declared:
            keys.extend(key for key in declared if key not in keys)
        stack.extend(dependant.dependencies)
    return tuple(keys)


def render() -> str:
    out: list[str] = [HEADER, ""]
    out.append("| Role | Inherits | Privileged | Permissions |")
    out.append("|---|---|---|---|")
    for spec in ROLE_SPECS:
        inherits = spec.inherits or "-"
        privileged = "yes" if spec.key in PRIVILEGED_ROLES else "no"
        out.append(f"| `{spec.key}` | {inherits} | {privileged} | {len(ROLE_PERMISSIONS[spec.key])} |")
    out.append("")
    for spec in ROLE_SPECS:
        out.append(f"- **`{spec.key}`** - {spec.name}. {spec.description}")
    out.append("")

    out.append("## Separation of duties")
    out.append("")
    out.append("Two roles nobody may hold at the same time. Seeded by `sync_catalog`, edited afterwards")
    out.append("by a super admin, which is why the rule lives in a table rather than in code.")
    out.append("")
    for a, b in SOD_PAIRS:
        out.append(f"- `{a}` + `{b}`")
    out.append("")

    out.append("## The permission catalog")
    out.append("")
    out.append("`privileged` means holding a role that carries this permission is a big deal: granting it")
    out.append("goes through a second approver, and (from the MFA work) forces enrolment.")
    out.append("")
    for category, permissions in BY_CATEGORY.items():
        out.append(f"### {category}")
        out.append("")
        out.append("| Key | Privileged | What it allows |")
        out.append("|---|---|---|")
        for permission in permissions:
            mark = "yes" if permission.is_privileged else ""
            out.append(f"| `{permission.key}` | {mark} | {permission.description} |")
        out.append("")

    out.append("## Role matrix")
    out.append("")
    out.append("Roles down, permissions across. A `+` is held, a blank is not.")
    out.append("")
    keys = [p.key for p in _catalog_in_order()]
    out.append("| Permission | " + " | ".join(spec.key for spec in ROLE_SPECS) + " |")
    out.append("|---" * (len(ROLE_SPECS) + 1) + "|")
    for key in keys:
        cells = ["+" if key in ROLE_PERMISSIONS[spec.key] else "" for spec in ROLE_SPECS]
        out.append(f"| `{key}` | " + " | ".join(cells) + " |")
    out.append("")

    out.append("## The route map")
    out.append("")
    out.append("What each endpoint asks for. A route with two keys is reachable either way - the caller")
    out.append("needs **any one** of them. Rows below the table are the routes with no permission check at")
    out.append("all, and each is public by design.")
    out.append("")
    guarded: list[tuple[str, str, str]] = []
    unguarded: list[str] = []
    for path, route in iter_api_routes(app):
        keys = guard_keys(route)
        for method in sorted(route.methods or set()):
            if method in ("HEAD", "OPTIONS"):
                continue
            if keys:
                guarded.append((path, method, " or ".join(f"`{key}`" for key in keys)))
            else:
                unguarded.append(f"`{method} {path}`")
    guarded.sort()
    out.append("| Path | Method | Requires |")
    out.append("|---|---|---|")
    for path, method, keys in guarded:
        out.append(f"| `{path}` | {method} | {keys} |")
    out.append("")
    out.append("No permission check, on purpose:")
    out.append("")
    for entry in unguarded:
        out.append(f"- {entry}")
    out.append("")
    return "\n".join(out)


def _catalog_in_order():
    for permissions in BY_CATEGORY.values():
        yield from permissions


def main() -> int:
    rendered = render()
    if "--check" in sys.argv:
        if not DEST.exists():
            print(f"  FAIL: {DEST} does not exist - run `python scripts/generate_rbac_doc.py`")
            return 1
        if DEST.read_text(encoding="utf-8") != rendered:
            print(f"  FAIL: {DEST.name} is stale - run `python scripts/generate_rbac_doc.py`")
            return 1
        print(f"  OK: {DEST.name} is up to date")
        return 0

    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(rendered, encoding="utf-8")
    print(f"  wrote {DEST} ({len(rendered)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
